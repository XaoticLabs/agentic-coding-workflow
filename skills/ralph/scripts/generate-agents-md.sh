#!/usr/bin/env bash
# Generates .claude/project-commands.json and .claude/AGENTS.md.
# Detects project commands while preserving existing structured overrides
# so Ralph iterations (and humans) know how to operate this project.

set -euo pipefail

PROJECT_DIR="${CLAUDE_PROJECT_DIR:-.}"
OUTPUT_FILE="${PROJECT_DIR}/.claude/AGENTS.md"
COMMANDS_SCRIPT="$(dirname "$(realpath "$0")")/../../../scripts/project-commands.py"

mkdir -p "$(dirname "$OUTPUT_FILE")"

# ── Project type detection (mirrors hooks/lint-on-stop.sh) ──────────────

detect_project() {
  local type="unknown"
  local lang=""
  local framework=""
  local build_cmd=""
  local test_cmd=""
  local lint_cmd=""
  local format_cmd=""
  local run_cmd=""

  # Share marker detection with Stop verification. Mixed roots must select
  # aggregate commands rather than inherit one language's defaults.
  local readiness readiness_status=0 project_languages
  readiness=$(python3 "$COMMANDS_SCRIPT" readiness "$PROJECT_DIR") || readiness_status=$?
  [ "$readiness_status" -le 1 ] || return "$readiness_status"
  project_languages=$(printf '%s' "$readiness" | jq -r '.languages | join(", ")')

  # Elixir / Phoenix
  if [[ "$project_languages" == *,* ]]; then
    type="mixed"
    lang="$project_languages"
  elif [ -f "${PROJECT_DIR}/mix.exs" ]; then
    type="elixir"
    lang="Elixir"
    build_cmd="mix compile"
    test_cmd="mix test"
    lint_cmd="mix credo"
    format_cmd="mix format"
    if grep -q "phoenix" "${PROJECT_DIR}/mix.exs" 2>/dev/null; then
      framework="Phoenix"
      run_cmd="mix phx.server"
    fi
  # Python
  elif [ -f "${PROJECT_DIR}/pyproject.toml" ] || [ -f "${PROJECT_DIR}/setup.py" ] || [ -f "${PROJECT_DIR}/setup.cfg" ] || [ -f "${PROJECT_DIR}/requirements.txt" ]; then
    type="python"
    lang="Python"
    # Python tooling must come from project-commands.json, based on the
    # project's CI/tool configuration or an explicitly selected profile.
    # Installed executables and pyproject.toml alone do not establish policy.
    if [ -f "${PROJECT_DIR}/manage.py" ]; then
      framework="Django"
      run_cmd="python manage.py runserver"
    elif grep -q "fastapi\|FastAPI" "${PROJECT_DIR}/pyproject.toml" 2>/dev/null; then
      framework="FastAPI"
      run_cmd="uvicorn main:app --reload"
    elif grep -q "flask\|Flask" "${PROJECT_DIR}/pyproject.toml" 2>/dev/null; then
      framework="Flask"
      run_cmd="flask run"
    fi
  # Node.js / TypeScript
  elif [ -f "${PROJECT_DIR}/package.json" ]; then
    type="node"
    if [ -f "${PROJECT_DIR}/tsconfig.json" ]; then
      lang="TypeScript"
    else
      lang="JavaScript"
    fi
    # Select actual workspace/package-manager tasks from project configuration.
    # A package.json or lockfile alone does not establish the CI commands.

    # Framework detection
    if [ -f "${PROJECT_DIR}/next.config.js" ] || [ -f "${PROJECT_DIR}/next.config.mjs" ] || [ -f "${PROJECT_DIR}/next.config.ts" ]; then
      framework="Next.js"
    elif [ -f "${PROJECT_DIR}/nuxt.config.ts" ]; then
      framework="Nuxt"
    fi
  # Go
  elif [ -f "${PROJECT_DIR}/go.mod" ] || [ -f "${PROJECT_DIR}/go.work" ]; then
    type="go"
    lang="Go"
    # Keep project-selected module/workspace scope and lint policy.
  # Rust
  elif [ -f "${PROJECT_DIR}/Cargo.toml" ]; then
    type="rust"
    lang="Rust"
    build_cmd="cargo build"
    test_cmd="cargo test"
    lint_cmd="cargo clippy"
    format_cmd="cargo fmt"
    run_cmd="cargo run"
  fi

  # ── Save defaults, then read the effective project overrides ──────────

  local init_options=()
  case "$type" in python|node|go|mixed|unknown) init_options+=(--omit-empty) ;; esac
  python3 "$COMMANDS_SCRIPT" init "${init_options[@]}" "$PROJECT_DIR" \
    "$build_cmd" "$test_cmd" "$lint_cmd" "$format_cmd" "$run_cmd"
  # Omitted actions remain unknown rather than silently disabled.
  # init validated the complete configuration above; get may now return 1.
  local action command status
  for action in build test lint format run; do
    if command=$(python3 "$COMMANDS_SCRIPT" get "$PROJECT_DIR" "$action"); then
      :
    else
      status=$?
      [ "$status" -eq 1 ] || return "$status"
      command=""
    fi
    case "$action" in
      build) build_cmd="$command" ;;
      test) test_cmd="$command" ;;
      lint) lint_cmd="$command" ;;
      format) format_cmd="$command" ;;
      run) run_cmd="$command" ;;
    esac
  done

  # ── Write AGENTS.md ──────────────────────────────────────────────────

  cat > "$OUTPUT_FILE" << AGENTS_EOF
# Project Operations Guide

> Auto-generated by \`generate-agents-md.sh\` — re-run to refresh.
> Commands come from \`.claude/project-commands.json\`; edit that file to customize them.

## Project Type

- **Language:** ${lang:-Unknown}
- **Framework:** ${framework:-None detected}
- **Type identifier:** ${type}

## Commands

| Action  | Command |
|---------|---------|
| Build   | \`${build_cmd:-N/A}\` |
| Test    | \`${test_cmd:-N/A}\` |
| Lint    | \`${lint_cmd:-N/A}\` |
| Format  | \`${format_cmd:-N/A}\` |
| Run     | \`${run_cmd:-N/A}\` |

## Workflow Rules

1. Select test/lint commands from existing CI/task configuration; missing commands are unconfigured, not passing.
2. Run configured checks before accepting work: test \`${test_cmd:-N/A}\`, lint \`${lint_cmd:-N/A}\`.
3. Formatting is separate and explicit: \`${format_cmd:-N/A}\`; verification must not apply fixes.
4. Honor required project checks and report unavailable or explicitly disabled actions. N/A is not evidence of success.

## Git Conventions

- Write descriptive commit messages (imperative mood, explain the "why")
- One logical change per commit
- Keep commits atomic and self-contained

## Notes

- If commands above show N/A, update \`.claude/project-commands.json\` and re-run the generator
- This file is used by Ralph loop iterations as the project operational guide
AGENTS_EOF

  echo "Generated ${OUTPUT_FILE}"
  echo "Project type: ${type} | Language: ${lang:-unknown} | Framework: ${framework:-none}"
}

detect_project
