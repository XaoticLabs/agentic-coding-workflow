#!/usr/bin/env python3
"""Generate Autolith resources from the shared workflow catalog."""

import json
from pathlib import Path

from host_resources import supporting_files


def lisp_string(value: str) -> str:
    """Quote data for Common Lisp, whose strings have no JSON escape syntax."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def role_capabilities(entry: dict) -> set[str]:
    """Apply canonical grants and explicit denies before host translation."""
    requested = entry.get("tools") or []
    denied = set(entry.get("disallowed_tools") or [])
    # Claude's unrestricted roles inherit tools; restricted roles state a list.
    inherited = {"Read", "Glob", "Grep", "Bash", "Write", "Edit", "Skill", "Agent"}
    return (set(requested) if requested else inherited) - denied


def role_tools(entry: dict) -> list[str]:
    """Translate effective capabilities without expanding restricted roles."""
    capabilities = role_capabilities(entry)
    mapped = []
    if "Read" in capabilities:
        mapped.append("resource.read")
    if capabilities.intersection({"Glob", "Grep"}):
        mapped.append("search.*")
    if capabilities.intersection({"Write", "Edit", "MultiEdit"}):
        mapped.append("resource.edit")
    if "Bash" in capabilities:
        mapped.append("shell.run")
    if "Skill" in capabilities:
        mapped.append("skill.load")
    return mapped


def role_spawns(name: str, entry: dict, available: dict) -> list[str]:
    """Preserve implementer delegation, enabling other roles only explicitly."""
    if "Agent" not in role_capabilities(entry):
        return []
    if name != "implementer" and "Agent" not in (entry.get("tools") or []):
        return []
    return sorted(role for role in available if role != name)


def generate(root: Path, catalog: dict) -> dict[str, str | bytes]:
    """Return portable generated files; the shared synchronizer owns writes."""
    output = {}
    operations = [";;; Generated by maak sync-hosts. Edit commands/ or skills/ instead.", "(in-package #:autolith)", ""]
    for group, kind in (("commands", "command"), ("skills", "skill")):
        for name, entry in sorted(catalog[group].items()):
            if entry["model_invocable"]:
                header = (
                    "---\n"
                    f"name: {name}\n"
                    f"description: {json.dumps(entry['description'], ensure_ascii=False)}\n"
                    "metadata:\n"
                    f"  workflow-source: {json.dumps(entry['source'])}\n"
                    "---\n\n"
                )
                output[f"hosts/autolith/skills/{name}/SKILL.md"] = header + entry["body"].rstrip() + "\n"
                if kind == "skill":
                    output.update(supporting_files(
                        root, entry["source"], f"hosts/autolith/skills/{name}", "autolith",
                    ))
            if entry["user_invocable"]:
                description = lisp_string(entry["description"])
                operations.extend([
                    f"(define-application-command workflow--{name}-command",
                    f'    (:name "/workflow-{name}" :argument "[ARGUMENTS]"',
                    f"     :description {description}",
                    '     :tip "runs the canonical agentic-coding-workflow instructions."',
                    "     :busy-behavior :hold :terminal-behavior :shared :callable t",
                    "     :slash-parser workflow-slash-arguments)",
                    '    (application &optional (arguments ""))',
                    f'  (workflow-invoke application "{kind}" "{name}" arguments)',
                    "  ':continue)",
                    "",
                ])
    output["hosts/autolith/generated/commands.lisp"] = "\n".join(operations)
    role_policy = {}
    for name, entry in sorted(catalog["agents"].items()):
        granted_tools = role_tools(entry)
        granted_spawns = role_spawns(name, entry, catalog["agents"])
        role_policy[name] = {"tools": granted_tools, "max_turns": entry.get("max_turns"),
                             "spawns": granted_spawns}
        tools = " ".join(lisp_string(tool) for tool in granted_tools)
        spawns = "(" + " ".join(lisp_string(role) for role in granted_spawns) + ")" if granted_spawns else "nil"
        effort = entry.get("effort") or "medium"
        if effort not in {"none", "minimal", "low", "medium", "high", "xhigh", "max"}:
            raise ValueError(f"Unsupported Autolith effort for {name}: {effort}")
        output[f"hosts/autolith/agents/{name}.sexp"] = (
            ";;; Generated by maak sync-hosts. Edit agents/ instead.\n"
            f"(:name {lisp_string(name)}\n"
            f" :description {lisp_string(entry['description'])}\n"
            f" :instructions {lisp_string(entry['body'])}\n"
            f" :tools ({tools})\n"
            f" :spawns {spawns}\n"
            ' :models ("@parent")\n'
            f" :reasoning-effort :{effort}\n"
            " :blocking-p t)\n"
        )
    output["hosts/autolith/generated/policy.json"] = json.dumps(role_policy, indent=2, sort_keys=True) + "\n"
    return output
