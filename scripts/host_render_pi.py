#!/usr/bin/env python3
"""Render Pi's native skills from the shared, source-derived host catalog."""

import json
from pathlib import Path

from host_resources import supporting_files


def generate(root: Path, catalog: dict) -> dict[str, str | bytes]:
    outputs = {}
    for kind in ("commands", "skills"):
        for name, entry in catalog[kind].items():
            directory = "skills" if entry["user_invocable"] else "model-skills"
            destination = f"hosts/pi/generated/{directory}/{name}"
            # Pi honors this field for model discovery. Explicit invocations
            # are registered by index.ts, including model-only entry rejection.
            header = (
                f"name: {name}\n"
                f"description: {json.dumps(entry['description'], ensure_ascii=False)}\n"
                f"disable-model-invocation: {str(not entry['model_invocable']).lower()}\n"
            )
            outputs[f"{destination}/SKILL.md"] = (
                "---\n" + header + "---\n\n"
                + "<!-- Generated by maak sync-hosts. Edit " + entry["source"] + ". -->\n\n"
                + entry["body"].rstrip() + "\n"
            )
            if kind != "skills":
                continue
            outputs.update(supporting_files(root, entry["source"], destination, "pi"))
    return outputs
